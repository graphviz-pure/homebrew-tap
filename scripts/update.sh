#!/usr/bin/env bash
# Rewrites Formula/graphviz-pure.rb for the latest verified release.
set -euo pipefail
cd "$(dirname "$0")/.."
if ! gh release view --repo graphviz-pure/graphviz-pure >/dev/null 2>&1; then
  echo "no release yet" >&2; exit 0
fi
version=$(scripts/fetch-verified.sh '*-apple-darwin*.tar.gz' '*-unknown-linux-musl*.tar.gz')
sha() { (cd dist && sha256sum "graphviz-pure-$version-$1.tar.gz" | cut -d' ' -f1); }
url() { echo "https://github.com/graphviz-pure/graphviz-pure/releases/download/v$version/graphviz-pure-$version-$1.tar.gz"; }
# A v3 archive must never silently become a single-binary install if its compat
# companion is missing. Old archives do not carry a launcher.
for target in x86_64-apple-darwin x86_64-unknown-linux-musl; do
  if tar -tzf "dist/graphviz-pure-$version-$target.tar.gz" | grep '/graphviz-pure-launcher$' > /dev/null; then
    test -f "dist/graphviz-pure-$version-$target-compat.tar.gz" ||
      { echo "missing compat archive for $target" >&2; exit 1; }
  fi
done
# Older releases have neither launcher nor compat assets. Keep generating their
# original formula until a release carrying both CPU variants is available.
compat_resource() {
  local target=$1
  [ -f "dist/graphviz-pure-$version-$target-compat.tar.gz" ] || return 0
  cat <<RB
      resource "compat" do
        url "$(url "$target-compat")"
        sha256 "$(sha "$target-compat")"
      end
RB
}
cat > Formula/graphviz-pure.rb <<RB
# Generated by scripts/update.sh from a release whose build provenance was verified.
class GraphvizPure < Formula
  desc "Pure-Rust port of Graphviz 16.1.0, same output on every platform (not affiliated with Graphviz)"
  homepage "https://graphviz-pure.github.io/"
  version "$version"
  license "EPL-2.0"

  on_macos do
    on_arm do
      url "$(url aarch64-apple-darwin)"
      sha256 "$(sha aarch64-apple-darwin)"
    end
    on_intel do
      url "$(url x86_64-apple-darwin)"
      sha256 "$(sha x86_64-apple-darwin)"
$(compat_resource x86_64-apple-darwin)
    end
  end

  on_linux do
    on_arm do
      url "$(url aarch64-unknown-linux-musl)"
      sha256 "$(sha aarch64-unknown-linux-musl)"
    end
    on_intel do
      url "$(url x86_64-unknown-linux-musl)"
      sha256 "$(sha x86_64-unknown-linux-musl)"
$(compat_resource x86_64-unknown-linux-musl)
    end
  end

  def install
    if (buildpath/"graphviz-pure-launcher").exist?
      (libexec/"v3").install "graphviz-pure"
      libexec.install "graphviz-pure-launcher" => "graphviz-pure"
      resource("compat").stage { (libexec/"compat").install "graphviz-pure" }
      bin.install_symlink libexec/"graphviz-pure"
    else
      bin.install "graphviz-pure"
    end
  end

  test do
    assert_match "<svg", pipe_output("#{bin}/graphviz-pure -Tsvg", "digraph { a -> b }")
  end
end
RB
echo "$version"
